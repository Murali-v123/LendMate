from django.contrib import admin

from .models import Notification


@admin.register(Notification)
class NotificationAdmin(admin.ModelAdmin):
    list_display = [
        "id",
        "channel",
        "notification_type",
        "borrower",
        "recipient_number",
        "status",
        "attempts",
        "created_at",
        "sent_at",
    ]
    list_filter = ["channel", "status", "notification_type", "created_at"]
    search_fields = [
        "borrower__full_name",
        "recipient_number",
        "message",
        "event_key",
        "provider_message_id",
    ]
    readonly_fields = [
        "event_key",
        "provider_message_id",
        "created_at",
        "updated_at",
        "sent_at",
        "next_retry_at",
    ]
    raw_id_fields = ["borrower", "loan", "payment", "lender"]
    date_hierarchy = "created_at"
    ordering = ["-created_at"]

    def has_add_permission(self, request):
        return False  # Notifications are generated by system workflows
